function normalizeCategory(value) {
  if (!value || typeof value !== 'string') return 'Cloud'
  const trimmed = value.trim()
  if (VALID.has(trimmed)) return trimmed
  const mapped = CATEGORY_MAP[trimmed.toLowerCase()]
  if (mapped) return mapped
  return 'Cloud'
}

// Run when executed directly: node scripts/normalize-catalog-categories.js
const catalogPath = new URL(
  '../data/expanded_certification _catalog.json',
  import.meta.url,
)
const fs = await import('fs')
const data = JSON.parse(fs.readFileSync(catalogPath, 'utf-8'))
const after = {}
const out = data.map((entry) => {
  const norm = normalizeCategory(entry.category)
  after[norm] = (after[norm] || 0) + 1
  return { ...entry, category: norm }
})
fs.writeFileSync(catalogPath, JSON.stringify(out, null, 2))
console.log('Normalized categories for', out.length, 'entries')
console.log(
  'Distribution:',
  Object.entries(after)
    .sort((a, b) => b[1] - a[1])
    .map(([c, n]) => `${c}: ${n}`)
    .join(', '),
)
